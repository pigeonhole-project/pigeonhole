//! docs/metrics.md lists every metric the code declares; regenerate with
//! `UPDATE_METRICS_DOC=1 cargo test -p pigeonhole --test metrics_doc`.

use pigeonhole_types::MetricKind;
use std::collections::HashSet;
use std::path::Path;

const BEGIN: &str = "<!-- metrics:begin (generated by tests/metrics_doc.rs) -->";
const END: &str = "<!-- metrics:end -->";

/// Histogram name suffixes `prometheus.rs` sets buckets for; any other
/// histogram would be exported as a summary.
const BUCKETED: &[&str] = &["_seconds", "_ratio", "_per_chunk", "_per_entry"];

fn table() -> String {
    let crates = ["pigeonhole-blob", "pigeonhole-meta", "pigeonhole (binary)"];
    let mut out = String::new();
    for (name, docs) in crates.iter().zip(pigeonhole::metric_docs()) {
        out.push_str(&format!("\n### {name}\n\n| Metric | Kind | Labels | Meaning |\n|---|---|---|---|\n"));
        for d in docs {
            let labels = d.labels.iter().map(|l| format!("`{l}`")).collect::<Vec<_>>().join(", ");
            out.push_str(&format!("| `{}` | {} | {} | {} |\n", d.name, d.kind.as_str(), labels, d.help.replace('|', "\\|")));
        }
    }
    out
}

#[test]
fn names_are_unique_and_histograms_have_buckets() {
    let mut seen = HashSet::new();
    for d in pigeonhole::metric_docs().into_iter().flatten() {
        assert!(d.name.starts_with("pigeonhole_"), "{}", d.name);
        assert!(seen.insert(d.name), "{} declared twice", d.name);
        if d.kind == MetricKind::Histogram {
            assert!(BUCKETED.iter().any(|s| d.name.ends_with(s)), "{}: no buckets for it in prometheus.rs", d.name);
        }
        if d.kind == MetricKind::Counter {
            assert!(d.name.ends_with("_total"), "{}: counters end in _total", d.name);
        }
    }
}

#[test]
fn docs_list_every_metric() {
    let path = Path::new(env!("CARGO_MANIFEST_DIR")).join("../../../docs/metrics.md");
    let doc = std::fs::read_to_string(&path).expect("docs/metrics.md");
    let (head, rest) = doc.split_once(BEGIN).expect("begin marker");
    let (_, tail) = rest.split_once(END).expect("end marker");
    let want = format!("{head}{BEGIN}\n{}\n{END}{tail}", table());
    if std::env::var_os("UPDATE_METRICS_DOC").is_some() {
        std::fs::write(&path, want).unwrap();
    } else {
        assert!(doc == want, "docs/metrics.md is stale: UPDATE_METRICS_DOC=1 cargo test -p pigeonhole --test metrics_doc");
    }
}
