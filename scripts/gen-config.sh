#!/usr/bin/env bash
# Write a temporary pigeonhole.toml for compat / CI runs.
#   CONFIG_OUT=... CONFIG_INSTANCE=memory ./scripts/gen-config.sh
#
# Recognized env (all optional except where noted):
#   CONFIG_OUT           output path (required)
#   CONFIG_INSTANCE      memory | telegram | discord (default memory)
#   CONFIG_SCOPE_ID      chat id (telegram) / channel id (discord); required for those
#   CONFIG_LISTEN_ADDR   default 0.0.0.0:8333
#   CONFIG_META_LOG      local metadata log directory (default pigeonhole-log)
#   CONFIG_REGION        default us-east-1
#   CONFIG_CHUNK_SIZE    default 19922944
#   CONFIG_CHUNK_CODEC   default zstd

set -euo pipefail

: "${CONFIG_OUT:?CONFIG_OUT required}"

INSTANCE="${CONFIG_INSTANCE:-memory}"
LISTEN_ADDR="${CONFIG_LISTEN_ADDR:-0.0.0.0:8333}"
META_LOG="${CONFIG_META_LOG:-pigeonhole-log}"
REGION="${CONFIG_REGION:-us-east-1}"
CHUNK_SIZE="${CONFIG_CHUNK_SIZE:-19922944}"
CHUNK_CODEC="${CONFIG_CHUNK_CODEC:-zstd}"
EXTRA_BG=""

case "$INSTANCE" in
  memory)
    INSTANCE_BLOCK=$'[[instances]]\nid = "mem"\nkind = "memory"'
    # MemoryBlobStore is process-local; quiet background tasks under heavy suites.
    EXTRA_BG=$'\n[repair]\nscrub = false\ninterval_secs = 3600\n\n[sweep]\ninterval_secs = 3600\n'
    ;;
  telegram)
    : "${CONFIG_SCOPE_ID:?CONFIG_SCOPE_ID (chat id) required for telegram}"
    INSTANCE_BLOCK="[[instances]]
id = \"tg\"
kind = \"telegram\"
chat_id = ${CONFIG_SCOPE_ID}"
    ;;
  discord)
    : "${CONFIG_SCOPE_ID:?CONFIG_SCOPE_ID (channel id) required for discord}"
    INSTANCE_BLOCK="[[instances]]
id = \"dc\"
kind = \"discord\"
channel_id = ${CONFIG_SCOPE_ID}"
    ;;
  *)
    echo "unknown CONFIG_INSTANCE=$INSTANCE (memory|telegram|discord)" >&2
    exit 1
    ;;
esac

mkdir -p "$(dirname "$CONFIG_OUT")"
cat >"$CONFIG_OUT" <<EOF
# generated by scripts/gen-config.sh — do not edit
listen_addr = "${LISTEN_ADDR}"
region = "${REGION}"

[meta.log]
kind = "local"
path = "${META_LOG}"

${INSTANCE_BLOCK}

[chunk]
size = ${CHUNK_SIZE}
codec = "${CHUNK_CODEC}"
block_size = 1048576

[ingest]
memory_budget = 268435456

[telegram]
send_rate_per_sec = 0.5
send_burst = 3.0
get_file_rate_per_sec = 15.0
get_file_burst = 30.0
delete_rate_per_sec = 1.0
delete_burst = 5.0
upload_concurrency = 2
download_concurrency = 8
${EXTRA_BG}
EOF
