#!/usr/bin/env bash
# A local pigeonhole on disk with Prometheus, Grafana and S3 traffic, to watch
# the metrics live (docs/metrics.md).
#
#   ./scripts/metrics-demo.sh up       # build, start everything (NO_LOAD=1: no traffic)
#   METRICS_DEMO_BACKEND=discord ./scripts/metrics-demo.sh up
#                                      # blobs, log and snapshots in the Discord channels
#                                      # DISCORD_{BLOBS,LOG,SNAP}_CHANNEL_ID of .env, gentler traffic
#   METRICS_DEMO_BACKEND=telegram …    # the same in TG_{BLOBS,LOG,SNAP}_CHAT_ID (MTProto, TG_BOT_TOKEN)
#   METRICS_DEMO_BOTS=2 …                # each chat store through two bots (…_TOKEN_2)
#   LOAD_CLIENTS=8 LOAD_PAUSE=0 …      # traffic shape (scripts/metrics-load.sh)
#   METRICS_DEMO_CACHE=off …           # no block cache (every read goes to the backend)
#   ./scripts/metrics-demo.sh check    # every dashboard query answers; every metric is documented
#   ./scripts/metrics-demo.sh status
#   ./scripts/metrics-demo.sh down     # stop (data stays in $STATE; `clean` removes it)
#
# Needs: prometheus, grafana, aws (brew install prometheus grafana awscli).
# Ports: S3 8333, /metrics 9100, Prometheus 9090, Grafana 3000.

set -euo pipefail

ROOT="$(cd "$(dirname "$0")/.." && pwd)"
BACKEND="${METRICS_DEMO_BACKEND:-disk}"
# Bots per chat store (1 or 2: TG_BOT_TOKEN_2 / DISCORD_BOT_TOKEN_2), docs/shared-limiter.md.
BOTS="${METRICS_DEMO_BOTS:-1}"
case "$BACKEND" in
  disk) STATE="${METRICS_DEMO_DIR:-$ROOT/.cache/metrics-demo}" ;;
  discord) STATE="${METRICS_DEMO_DIR:-$ROOT/.cache/metrics-demo-discord}" ;;
  telegram) STATE="${METRICS_DEMO_DIR:-$ROOT/.cache/metrics-demo-telegram}" ;;
  *) echo "METRICS_DEMO_BACKEND: disk | discord | telegram" >&2; exit 2 ;;
esac
OBS="$ROOT/ops/observability"
S3_ADDR=127.0.0.1:8333
METRICS_ADDR=127.0.0.1:9100
PROM_ADDR=127.0.0.1:9090
GRAFANA_PORT=3000

if [[ -f "$ROOT/.env" ]]; then
  set -a
  # shellcheck disable=SC1091
  source "$ROOT/.env"
  set +a
fi

need() { command -v "$1" >/dev/null || { echo "missing dependency: $1 ($2)" >&2; exit 1; }; }

running() { [[ -f "$STATE/$1.pid" ]] && kill -0 "$(cat "$STATE/$1.pid")" 2>/dev/null; }

# start NAME CMD...: run in the background, log to $STATE/NAME.log.
start() {
  local name="$1"
  shift
  if running "$name"; then
    echo "$name already running (pid $(cat "$STATE/$name.pid"))"
    return
  fi
  nohup "$@" >"$STATE/$name.log" 2>&1 &
  echo $! >"$STATE/$name.pid"
}

# wait_http NAME URL: until URL answers 2xx.
wait_http() {
  for _ in $(seq 1 100); do
    curl -fs -o /dev/null "$2" && return
    running "$1" || { echo "$1 exited; see $STATE/$1.log" >&2; exit 1; }
    sleep 0.2
  done
  echo "$1 did not come up; see $STATE/$1.log" >&2
  exit 1
}

grafana_home() {
  if [[ -n "${GRAFANA_HOME:-}" ]]; then
    echo "$GRAFANA_HOME"
  elif command -v brew >/dev/null && [[ -d "$(brew --prefix grafana 2>/dev/null)/share/grafana" ]]; then
    echo "$(brew --prefix grafana)/share/grafana"
  else
    echo "set GRAFANA_HOME to Grafana's homepath (the dir with conf/ and public/)" >&2
    exit 1
  fi
}

write_config() {
  case "$BACKEND" in
    disk) write_disk_config ;;
    discord) write_discord_config ;;
    telegram) write_telegram_config ;;
  esac
  if [[ "${METRICS_DEMO_CACHE:-on}" == off ]]; then
    printf '\n[cache]\nenabled = false\n' >>"$STATE/pigeonhole.toml"
  fi
}

write_disk_config() {
  cat >"$STATE/pigeonhole.toml" <<EOF
# generated by scripts/metrics-demo.sh
listen_addr = "$S3_ADDR"
region = "us-east-1"

[[store]]
id = "meta"
kind = "local_disk"
path = "$STATE/meta"

[[store]]
id = "disk"
kind = "local_disk"
path = "$STATE/blobs"

[meta]
log = "meta"
snapshot_every_entries = 2000
snapshot_every = "1m"

[chunk]
store = "disk"
size = "4 MiB"
codec = "zstd"

[sweep]
interval = "15s"

[repair]
interval = "10s"

[metrics]
enabled = true
listen_addr = "$METRICS_ADDR"
EOF
}

# Blobs, the log and snapshots each in a channel of their own (a store serves
# one purpose). The sweeper deletes every blob of ours in the blobs channel
# this tablet does not know.
write_discord_config() {
  local id bots='["DISCORD_BOT_TOKEN"]'
  if [[ "$BOTS" == 2 ]]; then
    bots='["DISCORD_BOT_TOKEN", "DISCORD_BOT_TOKEN_2"]'
    [[ -n "${DISCORD_BOT_TOKEN_2:-}" ]] || { echo "DISCORD_BOT_TOKEN_2 is not set (.env)" >&2; exit 1; }
  fi
  for id in DISCORD_BOT_TOKEN DISCORD_BLOBS_CHANNEL_ID DISCORD_LOG_CHANNEL_ID DISCORD_SNAP_CHANNEL_ID; do
    [[ -n "${!id:-}" ]] || { echo "$id is not set (.env)" >&2; exit 1; }
  done
  cat >"$STATE/pigeonhole.toml" <<EOF
# generated by scripts/metrics-demo.sh (discord)
listen_addr = "$S3_ADDR"
region = "us-east-1"

[[store]]
id = "dc-blobs"
kind = "discord"
channel_id = $DISCORD_BLOBS_CHANNEL_ID
bot_token_envs = $bots

[[store]]
id = "dc-log"
kind = "discord"
channel_id = $DISCORD_LOG_CHANNEL_ID
bot_token_envs = $bots

[[store]]
id = "dc-snap"
kind = "discord"
channel_id = $DISCORD_SNAP_CHANNEL_ID
bot_token_envs = $bots

[meta]
log = "dc-log"
snapshot = "dc-snap"
snapshot_every_entries = 500
snapshot_every = "5m"

[chunk]
store = "dc-blobs"
size = "16 MiB"
codec = "zstd"

[sweep]
interval = "60s"

[repair]
interval = "30s"

[metrics]
enabled = true
listen_addr = "$METRICS_ADDR"
EOF
}

# As write_discord_config, over MTProto as a bot (the session file caches
# the login).
write_telegram_config() {
  local id bots='["TG_BOT_TOKEN"]' session="session = \"$STATE/tg.session\""
  if [[ "$BOTS" == 2 ]]; then
    # A session file per bot, by default in the working directory.
    bots='["TG_BOT_TOKEN", "TG_BOT_TOKEN_2"]'
    session=""
    [[ -n "${TG_BOT_TOKEN_2:-}" ]] || { echo "TG_BOT_TOKEN_2 is not set (.env)" >&2; exit 1; }
  fi
  for id in TG_BOT_TOKEN TG_API_ID TG_API_HASH TG_BLOBS_CHAT_ID TG_LOG_CHAT_ID TG_SNAP_CHAT_ID; do
    [[ -n "${!id:-}" ]] || { echo "$id is not set (.env)" >&2; exit 1; }
  done
  local store
  cat >"$STATE/pigeonhole.toml" <<EOF
# generated by scripts/metrics-demo.sh (telegram)
listen_addr = "$S3_ADDR"
region = "us-east-1"
EOF
  for store in "tg-blobs $TG_BLOBS_CHAT_ID" "tg-log $TG_LOG_CHAT_ID" "tg-snap $TG_SNAP_CHAT_ID"; do
    set -- $store
    cat >>"$STATE/pigeonhole.toml" <<EOF

[[store]]
id = "$1"
kind = "telegram"
chat_id = $2
bot_token_envs = $bots
api_id_env = "TG_API_ID"
api_hash_env = "TG_API_HASH"
$session
EOF
  done
  cat >>"$STATE/pigeonhole.toml" <<EOF

[meta]
log = "tg-log"
snapshot = "tg-snap"
snapshot_every_entries = 500
snapshot_every = "5m"

[chunk]
store = "tg-blobs"
size = "16 MiB"
codec = "zstd"

[sweep]
interval = "60s"

[repair]
interval = "30s"

[metrics]
enabled = true
listen_addr = "$METRICS_ADDR"
EOF
}

up() {
  need prometheus "brew install prometheus"
  need grafana "brew install grafana"
  need aws "brew install awscli"
  mkdir -p "$STATE"
  (cd "$ROOT" && cargo build --release -q)
  write_config

  PIGEONHOLE_CONFIG="$STATE/pigeonhole.toml" start pigeonhole "$ROOT/target/release/pigeonhole"
  wait_http pigeonhole "http://$METRICS_ADDR/metrics"
  # /metrics answers before the tablet boots; S3 once it has (a chat log
  # takes seconds). Any HTTP answer will do: unsigned requests are refused.
  for _ in $(seq 1 600); do
    [[ "$(curl -s -o /dev/null -w '%{http_code}' "http://$S3_ADDR/" || true)" != 000 ]] && break
    running pigeonhole || { echo "pigeonhole exited; see $STATE/pigeonhole.log" >&2; exit 1; }
    sleep 0.5
  done

  start prometheus prometheus --config.file="$OBS/prometheus.yml" \
    --storage.tsdb.path="$STATE/prometheus" --web.listen-address="$PROM_ADDR"
  wait_http prometheus "http://$PROM_ADDR/-/ready"

  # Grafana 12+ ships the Prometheus data source as a plugin it fetches.
  local home g="$STATE/grafana"
  home="$(grafana_home)"
  mkdir -p "$g/plugins"
  if [[ ! -d "$g/plugins/prometheus" ]]; then
    grafana cli --homepath "$home" --pluginsDir "$g/plugins" plugins install prometheus >/dev/null
  fi
  python3 "$OBS/dashboard.py" >"$OBS/grafana/dashboards/pigeonhole.json"
  GF_PATHS_DATA="$g/data" GF_PATHS_LOGS="$g/logs" GF_PATHS_PLUGINS="$g/plugins" \
    GF_PATHS_PROVISIONING="$OBS/grafana/provisioning" PIGEONHOLE_DASHBOARDS="$OBS/grafana/dashboards" \
    GF_SERVER_HTTP_ADDR=127.0.0.1 GF_SERVER_HTTP_PORT="$GRAFANA_PORT" \
    GF_AUTH_ANONYMOUS_ENABLED=true GF_AUTH_ANONYMOUS_ORG_ROLE=Admin GF_AUTH_DISABLE_LOGIN_FORM=true \
    GF_DASHBOARDS_DEFAULT_HOME_DASHBOARD_PATH="$OBS/grafana/dashboards/pigeonhole.json" \
    GF_ANALYTICS_REPORTING_ENABLED=false GF_ANALYTICS_CHECK_FOR_UPDATES=false \
    start grafana grafana server --homepath "$home"
  wait_http grafana "http://127.0.0.1:$GRAFANA_PORT/api/health"

  if [[ -z "${NO_LOAD:-}" ]]; then
    # A chat store: few clients, long pauses (its rate limits, and every
    # write lands in the channels).
    local pause=0 clients=4
    [[ "$BACKEND" == discord ]] && pause=20 clients=3
    ENDPOINT="http://$S3_ADDR" LOAD_PAUSE="${LOAD_PAUSE:-$pause}" LOAD_CLIENTS="${LOAD_CLIENTS:-$clients}" \
      start load "$ROOT/scripts/metrics-load.sh"
  fi
  status
  echo
  echo "dashboard:  http://127.0.0.1:$GRAFANA_PORT/d/pigeonhole/pigeonhole"
}

# Every dashboard query answers through Grafana, and every metric the
# process exports is in docs/metrics.md.
check() {
  python3 - "$OBS/grafana/dashboards/pigeonhole.json" "$GRAFANA_PORT" <<'EOF'
import json, sys, urllib.request
dash, port = sys.argv[1], sys.argv[2]
bad = empty = 0
for p in json.load(open(dash))["panels"]:
    for t in p.get("targets", []):
        body = json.dumps({"queries": [{"refId": "A", "datasource": {"uid": "prom"}, "instant": True,
                                        "expr": t["expr"].replace("$__rate_interval", "1m")}],
                           "from": "now-5m", "to": "now"}).encode()
        req = urllib.request.Request(f"http://127.0.0.1:{port}/api/ds/query", body, {"Content-Type": "application/json"})
        res = json.load(urllib.request.urlopen(req))["results"]["A"]
        if res.get("error"):
            bad += 1
            print(f"ERROR  {p['title']}: {res['error']}")
        elif not any((f.get("data", {}).get("values") or [[]])[0] for f in res.get("frames", [])):
            empty += 1
            print(f"empty  {p['title']}: {t['expr'][:90]}")
print(f"{bad} failing, {empty} without data (a chat-only or idle metric is fine)")
sys.exit(1 if bad else 0)
EOF
  local undocumented
  undocumented="$(curl -fs "http://$METRICS_ADDR/metrics" | grep -Eo '^(pigeonhole|openraft_chat)_[a-z0-9_]*' \
    | sed -E 's/_(bucket|sum|count)$//' | sort -u \
    | while read -r m; do grep -q "\`$m\`" "$ROOT/docs/metrics.md" || echo "$m"; done)"
  if [[ -n "$undocumented" ]]; then
    echo "not in docs/metrics.md:" $undocumented >&2
    exit 1
  fi
  echo "every exported metric is documented"
}

status() {
  for name in pigeonhole prometheus grafana load; do
    if running "$name"; then
      echo "$name: running (pid $(cat "$STATE/$name.pid"), log $STATE/$name.log)"
    else
      echo "$name: stopped"
    fi
  done
}

# kill_tree PID: the process and everything it started (the load's clients
# and their aws calls).
kill_tree() {
  local child
  for child in $(pgrep -P "$1"); do
    kill_tree "$child"
  done
  kill "$1" 2>/dev/null || true
}

down() {
  for name in load grafana prometheus pigeonhole; do
    if running "$name"; then
      kill_tree "$(cat "$STATE/$name.pid")"
      echo "stopped $name"
    fi
    rm -f "$STATE/$name.pid"
  done
}

case "${1:-}" in
  up) up ;;
  check) check ;;
  status) status ;;
  down) down ;;
  clean) down; rm -rf "$STATE" ;;
  *) sed -n '2,12p' "$0"; exit 2 ;;
esac
